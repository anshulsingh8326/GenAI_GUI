export interface ComposerState {
  text: string
  attachments: Attachment[]
  modelId: string
  ratio: string
  width: number
  height: number
  batch: number
  enhance: boolean
  loras: LoraRef[]
  advanced: AdvancedParams
}

export interface ChatMessage {
  id: string
  role: 'user' | 'assistant'
  text?: string
  attachments?: Attachment[]
  jobId?: string
  createdAt: number
}

// -- jobs --------------------------------------------------------------------

export type JobStatus = 'queued' | 'running' | 'done' | 'error'
export type StageStatus = 'pending' | 'running' | 'done' | 'skipped' | 'error'

export interface Stage {
  id: string
  label: string
  status: StageStatus
  detail?: string
  durationMs?: number
}

export interface JobRecord {
  id: string
  createdAt: number
  status: JobStatus
  progress: number
  tab: string
  modelId: string
  modelName: string
  recipe: string
  prompt: string
  enhancedPrompt?: string
  seed: number
  params: AdvancedParams
  stages: Stage[]
  resultIds: string[]
}

/** POST /api/jobs payload - id/createdAt/status/progress/resultIds are backend-owned. */
export interface NewJobDraft {
  tab: string
  modelId: string
  modelName: string
  recipe: string
  prompt: string
  seed: number
  params: AdvancedParams
  stages: Stage[]
}

/** POST /api/jobs/{id}/mock-complete response (mock phase: placeholder outputs). */
export interface MockCompleteResult {
  job: JobRecord
  assets: Asset[]
}

