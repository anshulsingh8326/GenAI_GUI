// -- backend settings contract (settings.json, /api/settings) -----------------

export interface ConnectionProfile {
  id: string
  name: string
  kind: 'comfyui' | 'ollama'
  url: string
  auth: string
}

/** The persisted settings document - exactly what the backend stores in settings.json. */
export interface SettingsValues {
  connections: { comfyui: { url: string }; ollama: { url: string } }
  profiles: ConnectionProfile[]
  activeProfiles: { comfyui: string; ollama: string }
  defaults: {
    imageModel: string
    upscaler: string
    textProvider: string
    enhanceModel: string
    describeModel: string
  }
  folders: { library: string; exports: string; imports: string; agentInbox: string }
  prompts: Record<string, string>
  autoFreeVram: boolean
  agentEnabled: boolean
  agentToken: string
  /** Optional .bat/.cmd/.exe that starts ComfyUI - GUI button or opt-in boot auto-start. */
  comfyuiLauncher: string
  /** Opt-in: start the launcher once at backend boot (skipped when ComfyUI is already reachable). */
  comfyuiLauncherAutoStart: boolean
  /** ComfyUI source folder (main.py + custom_nodes + models) for content management. */
  comfyuiFolder: string
}

export interface SettingsEnvelope {
  values: SettingsValues
  /** false = settings.json does not exist yet -> the GUI pushes its current settings in on first connect. */
  initialized: boolean
}

export interface FolderValidation {
  ok: boolean
  path: string
  resolved: string
  exists: boolean
  isDir: boolean
  writable: boolean
  created: boolean
  message: string
}

export interface SystemInfo {
  app: string
  version: string
  python: string
  platform: string
  dataDir: string
  settingsFile: string
  settingsInitialized: boolean
  dbFile: string
  dbTables: string[]
}

// -- ComfyUI content management (Phase A: read-only) ---------------------------

export interface ComfyNodeInfo {
  name: string
  /** git origin when the node was cloned (null for zip/no-git installs) */
  source: string | null
  commit: string | null
  disabled: boolean
}

export interface ComfyModelStat {
  category: string
  files: number
  bytes: number
  items: ComfyModelFile[]
  truncated: boolean
}

export interface ComfyModelFile {
  /** path relative to the category folder, e.g. `subdir/model.safetensors` */
  name: string
  sizeBytes: number
  /** best-effort kind from the header: image / video / lora / vae / text_encoder / ... */
  kind: string
  /** short architecture tag when known (qwen_image, mmdit, vae, llm, ...) */
  arch: string | null
  /** LoRA base model when the header declares one */
  base: string | null
  /** LoRA trigger words from training metadata */
  triggers: string[]
  /** set when the file sits in the wrong category (the app never moves it) */
  suggestedCategory: string | null
}

export interface ComfyInspect {
  configured: string
  path: string
  valid: boolean
  mainPy: boolean
  flavor: 'portable' | 'venv' | 'unknown' | null
  pythonPath: string | null
  version: string | null
  customNodesDir: string | null
  modelsDir: string | null
  customNodes: ComfyNodeInfo[]
  customNodesTruncated: boolean
  models: ComfyModelStat[]
  extraModelPathsFile: boolean
  /** ComfyUI source folders derived from the launcher (only when no folder is configured). */
  suggestions: string[]
  error: string | null
}

export interface ComfyRequirementNode {
  name: string
  repo: string
  commit: string
  optional: boolean
  why: string
  /** Python module for package-style installs (ComfyUI 0.30+ Manager), else "" */
  package: string
  /** pip spec for package-style installs, else "" */
  pip: string
  /** true/false = checked; null = no ComfyUI folder configured yet. */
  installed: boolean | null
  installedPath: string | null
  installedCommit: string | null
}

export interface ComfyRequirementModel {
  name: string
  target: string
  sizeBytes: number | null
  optional: boolean
  why: string
  installed: boolean | null
  path: string | null
  sizeMatches: boolean | null
}

export interface ComfyCoreRequirements {
  nodes: ComfyRequirementNode[]
  models: ComfyRequirementModel[]
  missingNodes: number
  missingModels: number
  /** false = no ComfyUI folder configured, nothing could be checked */
  checked: boolean
  ready: boolean
}

export interface ComfyModuleRequirements {
  id: string
  name: string
  nodes: ComfyRequirementNode[]
  models: ComfyRequirementModel[]
  missingNodes: number
  missingModels: number
  /** false = no ComfyUI folder configured, nothing could be checked */
  checked: boolean
  ready: boolean
  error: string | null
}

export interface ComfyRequirements {
  inspect: ComfyInspect
  /** shared baseline every module relies on (GGUF loader, recommended Manager, ...) */
  core: ComfyCoreRequirements
  modules: ComfyModuleRequirements[]
}

export interface ComfyInstallTask {
  id: string
  moduleId: string
  moduleName: string
  nodeName: string
  action: 'pip' | 'clone' | 'update'
  target: string
  repo: string
  commit: string
  status: 'running' | 'succeeded' | 'failed'
  stage: string
  log: string[]
  error: string | null
  warning: string | null
  restartRequired: boolean
  startedAt: string
  finishedAt: string | null
}

export interface ComfyRestartResult {
  restarted: boolean
  endpoint: string | null
  message: string
}
