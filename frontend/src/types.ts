// ---------------------------------------------------------------------------
// Shared types for the GUI. Settings, connections, jobs and library assets all
// match the real backend contract; only generation itself is still simulated.
// ---------------------------------------------------------------------------

export type ThemeId = 'pastel-dark' | 'pastel-light'
export type AccentId = 'lavender' | 'mint' | 'peach' | 'sky'

// -- models -----------------------------------------------------------------

export interface ModelDefaults {
  steps: number
  cfg: number
  sampler: string
  scheduler: string
  denoise: number
}

export interface ModelOption {
  id: string
  name: string
  family: string
  kind: 'image' | 'upscale' | 'text'
  vram?: string
  installed: boolean
  note?: string
  badges: string[]
  defaults?: ModelDefaults
}

export interface LoraOption {
  id: string
  name: string
  family: string
  defaultStrength: number
}

export interface LoraRef {
  id: string
  strength: number
  on: boolean
}

// -- chat / composer ---------------------------------------------------------

export interface Attachment {
  id: string
  url: string
  name: string
  source: 'upload' | 'library'
  identity: boolean
  describe: boolean
  describeMode: 'character' | 'full'
}

export interface AdvancedParams {
  seed: number
  lockSeed: boolean
  steps: number
  cfg: number
  sampler: string
  scheduler: string
  denoise: number
  recipe: string
  refine: {
    on: boolean
    steps: number
    cfg: number
    denoise: number
    scale: number
  }
}

export interface ComposerState {
  text: string
  attachments: Attachment[]
  modelId: string
  ratio: string
  width: number
  height: number
  batch: number
  enhance: boolean
  loras: LoraRef[]
  advanced: AdvancedParams
}

export interface ChatMessage {
  id: string
  role: 'user' | 'assistant'
  text?: string
  attachments?: Attachment[]
  jobId?: string
  createdAt: number
}

// -- jobs --------------------------------------------------------------------

export type JobStatus = 'queued' | 'running' | 'done' | 'error'
export type StageStatus = 'pending' | 'running' | 'done' | 'skipped' | 'error'

export interface Stage {
  id: string
  label: string
  status: StageStatus
  detail?: string
  durationMs?: number
}

export interface JobRecord {
  id: string
  createdAt: number
  status: JobStatus
  progress: number
  tab: string
  modelId: string
  modelName: string
  recipe: string
  prompt: string
  enhancedPrompt?: string
  seed: number
  params: AdvancedParams
  stages: Stage[]
  resultIds: string[]
}

/** POST /api/jobs payload - id/createdAt/status/progress/resultIds are backend-owned. */
export interface NewJobDraft {
  tab: string
  modelId: string
  modelName: string
  recipe: string
  prompt: string
  seed: number
  params: AdvancedParams
  stages: Stage[]
}

/** POST /api/jobs/{id}/mock-complete response (mock phase: placeholder outputs). */
export interface MockCompleteResult {
  job: JobRecord
  assets: Asset[]
}

// -- library -----------------------------------------------------------------

export interface Asset {
  id: string
  url: string
  /** Smaller JPEG rendition (generated by the backend on first request); absent on session-only mock assets. */
  thumbUrl?: string
  label: string
  prompt: string
  model: string
  seed: number
  createdAt: number
  favorite: boolean
  tags: string[]
  nsfw?: boolean
  width?: number | null
  height?: number | null
  bytes?: number | null
  originJob?: string | null
}

// -- loose domain fixtures ---------------------------------------------------

export interface CharacterProfile {
  id: string
  name: string
  refs: number
  description: string
  avatar: string
  loras: string[]
}

export interface Preset {
  id: string
  name: string
  category: string
  description: string
  tags: string[]
}

// -- connections / resources -------------------------------------------------

/** Live connection state of one engine - owned by the engine store, fed by GET /api/status. */
export interface ConnRuntime {
  connected: boolean
  checking: boolean
  detail: string
}

export interface LoadedModel {
  id: string
  name: string
  sizeGb: number
  expiresInMin?: number
}

export interface EngineModelInfo {
  name: string
  sizeGb: number
}

export interface ComfyStatus {
  connected: boolean
  url: string
  detail: string
  version: string | null
  gpuName: string | null
  vramTotalGb: number | null
  vramFreeGb: number | null
  queue: { running: number; pending: number }
  /** Models loaded by app jobs (ComfyUI itself has no loaded-models API). */
  loaded: LoadedModel[]
}

export interface OllamaStatus {
  connected: boolean
  url: string
  detail: string
  installed: EngineModelInfo[]
  loaded: LoadedModel[]
}

/** Hardware usage - null means "unknown" (e.g. ComfyUI offline). */
export interface ResourceStats {
  vramUsedGb: number | null
  vramTotalGb: number | null
  ramUsedGb: number | null
  ramTotalGb: number | null
}

/** GET /api/status - one snapshot for the top bar and Resources popover. */
export interface StatusSnapshot {
  comfyui: ComfyStatus
  ollama: OllamaStatus
  resources: ResourceStats
}

export interface ConnTestResult {
  connected: boolean
  detail: string
}

export interface EngineActionResult {
  ok: boolean
  message: string
}

// -- backend settings contract (settings.json, /api/settings) -----------------

export interface ConnectionProfile {
  id: string
  name: string
  kind: 'comfyui' | 'ollama'
  url: string
  auth: string
}

/** The persisted settings document - exactly what the backend stores in settings.json. */
export interface SettingsValues {
  connections: { comfyui: { url: string }; ollama: { url: string } }
  profiles: ConnectionProfile[]
  activeProfiles: { comfyui: string; ollama: string }
  defaults: {
    imageModel: string
    upscaler: string
    textProvider: string
    enhanceModel: string
    describeModel: string
  }
  folders: { library: string; exports: string; imports: string; agentInbox: string }
  prompts: Record<string, string>
  autoFreeVram: boolean
  agentEnabled: boolean
  agentToken: string
}

export interface SettingsEnvelope {
  values: SettingsValues
  /** false = settings.json does not exist yet -> the GUI pushes its current settings in on first connect. */
  initialized: boolean
}

export interface FolderValidation {
  ok: boolean
  path: string
  resolved: string
  exists: boolean
  isDir: boolean
  writable: boolean
  created: boolean
  message: string
}

export interface SystemInfo {
  app: string
  version: string
  python: string
  platform: string
  dataDir: string
  settingsFile: string
  settingsInitialized: boolean
  dbFile: string
  dbTables: string[]
}
